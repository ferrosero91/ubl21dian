"""
Sign - Abstract base class for XML signing
Ported from PHP Sign class
"""
from abc import ABC, abstractmethod
from lxml import etree
from .utils import DIANUtils


class Sign(DIANUtils, ABC):
    """Abstract base class for XML digital signatures"""
    
    def __init__(self, path_certificate=None, password=None, xml_string=None):
        super().__init__()
        self.path_certificate = path_certificate
        self.password = password
        self.xml_string = xml_string
        
        self.read_certs()
        self.identifiers_references()
        
        if self.xml_string is not None:
            self.sign()

    @abstractmethod
    def load_xml(self):
        """Abstract method to load and process XML - must be implemented by subclasses"""
        pass

    @property
    def document(self):
        """Get the DOM document"""
        return self.dom_document

    def get_document(self):
        """Get the DOM document (PHP compatibility)"""
        return self.dom_document

    def sign(self, string=None):
        """Sign the XML document"""
        if string is not None:
            self.xml_string = string
            
        if self.xml_string is not None:
            self.load_xml()
            
            if self.dom_document is not None:
                # Convert to string
                if hasattr(self.dom_document, 'getroot'):
                    self.xml = etree.tostring(
                        self.dom_document.getroot(), 
                        encoding=self.encoding
                    ).decode(self.encoding)
                else:
                    self.xml = etree.tostring(
                        self.dom_document, 
                        encoding=self.encoding
                    ).decode(self.encoding)
                
                # Post-process to fix namespace prefixes (lxml generates ns0:, ns1:, etc.)
                self.xml = self._fix_namespace_prefixes(self.xml)
                
        return self

    def _fix_namespace_prefixes(self, xml_str):
        """Fix namespace prefixes generated by lxml to match PHP output"""
        import re
        
        # Map of namespace URIs to their preferred prefixes
        ns_prefix_map = {
            'http://www.w3.org/2000/09/xmldsig#': 'ds',
            'http://uri.etsi.org/01903/v1.3.2#': 'xades',
            'http://uri.etsi.org/01903/v1.4.1#': 'xades141',
        }
        
        result = xml_str
        
        # Find all ns0, ns1, etc. prefixes and their namespace declarations
        # Pattern: xmlns:nsX="namespace_uri"
        ns_pattern = re.compile(r'xmlns:(ns\d+)="([^"]+)"')
        
        # Find all namespace declarations
        ns_declarations = ns_pattern.findall(result)
        
        for auto_prefix, ns_uri in ns_declarations:
            if ns_uri in ns_prefix_map:
                target_prefix = ns_prefix_map[ns_uri]
                # Replace the auto-generated prefix with the correct one
                # Replace xmlns:nsX="uri" with xmlns:ds="uri"
                result = result.replace(f'xmlns:{auto_prefix}="{ns_uri}"', f'xmlns:{target_prefix}="{ns_uri}"')
                # Replace <nsX: with <ds:
                result = result.replace(f'<{auto_prefix}:', f'<{target_prefix}:')
                # Replace </nsX: with </ds:
                result = result.replace(f'</{auto_prefix}:', f'</{target_prefix}:')
        
        return result
